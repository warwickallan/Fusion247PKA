// Fusion247 Cockpit — ORIGIN BOUNDARY CHECK for services/cockpit/private-api.mjs.
//
// THE QUESTION THIS GATE ANSWERS, and it is a question about the product rather than about a header:
//
//   Can a webpage the operator did not authorise, running in the operator's own browser, use the
//   Cockpit as a deputy — to READ a private upstream's response, or to CAUSE AN ACTION against it —
//   without an authority the operator deliberately granted?
//
// The gate exists to make the answer NO by execution, and the deciding half is the SECOND one. A
// response header can only govern whether a page may read what has already happened; it cannot
// un-send the request. A browser is permitted to send some requests without asking in advance, so a
// boundary that lived only in the response would let those arrive at the upstream and take effect
// whatever the response said afterwards. Every refusal assertion below therefore checks THREE
// things: the status, the absence of any cross-origin read permission, and — the one that matters —
// WHAT THE UPSTREAM ACTUALLY RECEIVED, which must be nothing at all.
//
// ── WHY THIS GATE CAN EXIST AT ALL ───────────────────────────────────────────────────────────────
// The handler used to live in `server.mjs`, and `server.mjs` imports `db.mjs`, which opens two
// production pools at module scope. NO GATE COULD EXECUTE IT — that is why the defect it now holds
// survived, and it is the durable lesson, not the header. `private-api.mjs` imports node builtins
// and `down-reason.mjs` only, so this file boots the REAL handler in-process, points it at a fake
// upstream that records every byte it receives, and asserts against both ends. No database, no
// credentials, no installed dependency tree: it runs on a bare CI checkout.
//
//   node services/cockpit/origin-boundary-check.mjs
//
// ── ON THE MUTATION SECTION ──────────────────────────────────────────────────────────────────────
// Non-vacuity is regenerated by the machine on every run. The fixtures below restore the permissive
// behaviour IN MEMORY, INSIDE THIS FILE ONLY — nothing permissive is ever written into the server's
// own code, not even temporarily. They are POLICY FIXTURES named for the property they remove; they
// are not a recipe, and this file deliberately contains no attacking page, no narrative and no
// upstream detail. A fixture that stopped turning assertions red would be a gate that had quietly
// stopped biting, which looks exactly like a clean run — so that case aborts loudly.
import http from 'node:http';
import { PRIVATE_API_PREFIX, originDecision, parseAllowedOrigins, privateApiCtx, servePrivateApi } from './private-api.mjs';

// ── assertion sink ───────────────────────────────────────────────────────────────────────────────
let ran = 0, failed = 0;
const sink = (name, cond, detail) => {
  ran++;
  if (cond) { console.log('  PASS  ' + name + (detail ? ' — ' + detail : '')); return; }
  failed++;
  console.error('  FAIL  ' + name + (detail ? ' — ' + detail : ''));
};

// ── the recording fake upstream ──────────────────────────────────────────────────────────────────
// It answers everything, and it remembers everything. "The upstream received nothing" is only a
// claim worth making against something that would have told us if it had.
function startRecordingUpstream() {
  const seen = [];
  const server = http.createServer((req, res) => {
    const chunks = [];
    req.on('data', (c) => chunks.push(c));
    req.on('end', () => {
      const body = Buffer.concat(chunks);
      seen.push({ method: req.method, url: req.url, headers: { ...req.headers }, body });
      if (req.url.startsWith('/redirects-elsewhere')) {
        res.writeHead(302, { location: 'http://somewhere-else.invalid/landing', 'content-type': 'text/plain' });
        res.end('moved');
        return;
      }
      res.writeHead(200, { 'content-type': 'application/json', 'cache-control': 'no-store' });
      res.end(JSON.stringify({ ok: true, saw: req.method }));
    });
  });
  return {
    server,
    seen,
    clear() { seen.length = 0; },
    count() { return seen.length; },
    bytes() { return seen.reduce((n, r) => n + r.body.length, 0); },
  };
}

const listen = (server) => new Promise((resolve) => server.listen(0, '127.0.0.1', () => resolve(server.address().port)));
const close = (server) => new Promise((resolve) => server.close(resolve));

// ── the probe ────────────────────────────────────────────────────────────────────────────────────
// `node:http` rather than `fetch`, deliberately: a gate about which headers arrive must control
// exactly which headers are sent, including the ones a higher-level client is entitled to manage.
function probe(port, { method = 'GET', path = '/private-api/thing', headers = {}, body = null } = {}) {
  return new Promise((resolve, reject) => {
    const req = http.request({ host: '127.0.0.1', port, method, path, headers }, (res) => {
      const chunks = [];
      res.on('data', (c) => chunks.push(c));
      res.on('end', () => resolve({ status: res.statusCode, headers: res.headers, body: Buffer.concat(chunks).toString('utf8') }));
    });
    req.on('error', reject);
    if (body !== null) req.write(body);
    req.end();
  });
}

const noReadPermission = (r) => !('access-control-allow-origin' in r.headers);

const FOREIGN = 'https://not-this-host.example';
const NAMED_IN_ALLOWLIST = 'https://named-by-configuration.example';
const PAYLOAD = 'payload-that-must-never-arrive';

// The content types a browser is allowed to send WITHOUT asking permission first. This list is the
// reason the boundary is on the request: for these, no advance question is ever put to us.
const UNANNOUNCED_WRITE_TYPES = [
  'text/plain;charset=UTF-8',
  'application/x-www-form-urlencoded',
  'multipart/form-data; boundary=----boundary',
];

// ── the battery ──────────────────────────────────────────────────────────────────────────────────
// A pure function of (port under test, recorder, sink), so the SAME battery runs against the real
// handler and against every permissive fixture. It executes a fixed set of assertions either way.
async function assess(port, up, ok) {
  const SELF = `http://127.0.0.1:${port}`;

  // ── the read half ──────────────────────────────────────────────────────────────────────────────
  up.clear();
  let r = await probe(port, { headers: { origin: FOREIGN } });
  ok('a read from an origin that is not this host is refused', r.status === 403, 'status ' + r.status);
  ok('a refused read grants no cross-origin read permission', noReadPermission(r));
  ok('a refused read never reaches the upstream', up.count() === 0, up.count() + ' request(s) recorded');

  // ── the advance question, when one is asked ────────────────────────────────────────────────────
  up.clear();
  r = await probe(port, { method: 'OPTIONS', headers: { origin: FOREIGN, 'access-control-request-method': 'DELETE' } });
  ok('an advance permission question from a foreign origin is refused', r.status === 403, 'status ' + r.status);
  ok('the bridge does not answer that question on the upstream behalf',
    !('access-control-allow-methods' in r.headers), r.headers['access-control-allow-methods'] || 'no allow-methods');
  ok('a refused advance question grants no cross-origin read permission', noReadPermission(r));
  ok('a refused advance question never reaches the upstream', up.count() === 0, up.count() + ' request(s) recorded');

  // ── the write half: the requests no advance question is ever asked about ───────────────────────
  for (const ct of UNANNOUNCED_WRITE_TYPES) {
    up.clear();
    r = await probe(port, {
      method: 'POST', path: '/private-api/act',
      headers: { origin: FOREIGN, 'content-type': ct, 'content-length': Buffer.byteLength(PAYLOAD) },
      body: PAYLOAD,
    });
    ok('an unannounced write from a foreign origin is refused — ' + ct, r.status === 403, 'status ' + r.status);
    ok('it delivers no request to the upstream — ' + ct, up.count() === 0, up.count() + ' request(s) recorded');
    ok('it delivers no byte of its body to the upstream — ' + ct, up.bytes() === 0, up.bytes() + ' byte(s) recorded');
    ok('it grants no cross-origin read permission — ' + ct, noReadPermission(r));
  }

  // ── an origin that is not a host at all ────────────────────────────────────────────────────────
  up.clear();
  r = await probe(port, { headers: { origin: 'null' } });
  ok('an opaque origin is not treated as this host', r.status === 403, 'status ' + r.status);
  ok('an opaque origin never reaches the upstream', up.count() === 0, up.count() + ' request(s) recorded');

  // ── the legitimate path still works ────────────────────────────────────────────────────────────
  // NOT a claim about any particular overlay — no caller of this route exists in this repository.
  // It is the claim that the boundary refuses only what it is meant to refuse.
  up.clear();
  r = await probe(port, {});
  ok('a request carrying no origin is forwarded', r.status === 200, 'status ' + r.status);
  ok('and it reaches the upstream exactly once', up.count() === 1, up.count() + ' request(s) recorded');

  up.clear();
  r = await probe(port, { headers: { origin: SELF } });
  ok('a request whose origin IS this host is forwarded', r.status === 200, 'status ' + r.status);
  ok('and it reaches the upstream exactly once', up.count() === 1, up.count() + ' request(s) recorded');
  ok('an allowed response still grants no cross-origin read permission', noReadPermission(r));

  up.clear();
  r = await probe(port, {
    method: 'POST', path: '/private-api/act',
    headers: { origin: SELF, 'content-type': 'text/plain', 'content-length': Buffer.byteLength(PAYLOAD) },
    body: PAYLOAD,
  });
  ok('a write whose origin IS this host is forwarded', r.status === 200, 'status ' + r.status);
  ok('and its body arrives at the upstream intact',
    up.count() === 1 && up.seen[0].body.toString('utf8') === PAYLOAD, up.bytes() + ' byte(s) recorded');

  up.clear();
  r = await probe(port, { headers: { origin: NAMED_IN_ALLOWLIST } });
  ok('an origin named in the optional allowlist is forwarded', r.status === 200, 'status ' + r.status);
  ok('and it reaches the upstream exactly once', up.count() === 1, up.count() + ' request(s) recorded');

  // ── properties that were already good and must not regress ────────────────────────────────────
  up.clear();
  r = await probe(port, { headers: { origin: SELF, cookie: 'session=do-not-forward', authorization: 'Bearer do-not-forward' } });
  ok('an allowed request forwards no cookie to the upstream',
    up.count() === 1 && !('cookie' in up.seen[0].headers), 'cookie ' + (up.seen[0] ? ('cookie' in up.seen[0].headers) : 'n/a'));
  ok('an allowed request forwards no authorization header to the upstream',
    up.count() === 1 && !('authorization' in up.seen[0].headers));

  up.clear();
  r = await probe(port, { path: '/private-api//not-this-host.example/x' });
  ok('a path that tries to name its own host is refused', r.status === 400, 'status ' + r.status);
  ok('and it never reaches the upstream', up.count() === 0, up.count() + ' request(s) recorded');

  up.clear();
  r = await probe(port, { path: '/private-api/redirects-elsewhere' });
  ok('an upstream redirect is neither followed nor handed to the browser',
    r.status === 302 && !('location' in r.headers), 'status ' + r.status + ', location ' + (r.headers.location || 'absent'));
}

// ── the permissive policy fixtures (in memory, this file only) ───────────────────────────────────
// Each flag removes ONE property the repair holds. Nothing here is written to disk and nothing here
// is reachable from the server.
function permissiveFixture(upstreamBase, flags) {
  return async (req, res) => {
    const incoming = new URL(req.url || '/', 'http://x');
    const rest = incoming.pathname.slice(PRIVATE_API_PREFIX.length) || '/';
    if (!rest.startsWith('/') || rest.startsWith('//')) {
      res.writeHead(400, { 'content-type': 'text/plain; charset=utf-8' });
      res.end('bad private API path');
      return;
    }
    const decision = flags.noRequestTimeDecision
      ? { allowed: true }
      : originDecision({ origin: req.headers.origin, host: req.headers.host, allowed: [] });
    if (!decision.allowed) {
      res.writeHead(403, { 'content-type': 'text/plain; charset=utf-8', 'cache-control': 'no-store' });
      res.end('refused');
      return;
    }
    let body;
    if (req.method !== 'GET' && req.method !== 'HEAD' && req.method !== 'OPTIONS') {
      const chunks = [];
      for await (const c of req) chunks.push(c);
      body = Buffer.concat(chunks);
    }
    if (flags.answersTheQuestionItself && req.method === 'OPTIONS') {
      res.writeHead(204, {
        'access-control-allow-origin': req.headers.origin || '*',
        'access-control-allow-methods': 'GET,POST,PUT,PATCH,DELETE,OPTIONS',
        'cache-control': 'no-store',
      });
      res.end();
      return;
    }
    const headers = { accept: req.headers.accept || '*/*' };
    if (req.headers['content-type']) headers['content-type'] = req.headers['content-type'];
    let upstream;
    try {
      upstream = await fetch(upstreamBase + rest + incoming.search, {
        method: req.method, headers, body, redirect: 'manual', signal: AbortSignal.timeout(10_000),
      });
    } catch {
      res.writeHead(502, { 'content-type': 'text/plain' });
      res.end('fixture upstream failed');
      return;
    }
    const out = { 'cache-control': 'no-store' };
    const ct = upstream.headers.get('content-type');
    if (ct) out['content-type'] = ct;
    if (flags.grantsReadPermissionToTheCaller && req.headers.origin) {
      out['access-control-allow-origin'] = req.headers.origin;
      out.vary = 'Origin';
    }
    res.writeHead(upstream.status, out);
    res.end(Buffer.from(await upstream.arrayBuffer()));
  };
}

const FIXTURES = {
  'the request-time origin decision is removed': { noRequestTimeDecision: true },
  'the decision is removed and the caller is granted read permission in the response':
    { noRequestTimeDecision: true, grantsReadPermissionToTheCaller: true },
  'the decision is removed and the bridge answers the advance question itself':
    { noRequestTimeDecision: true, answersTheQuestionItself: true },
  'all three properties are removed — the handler as it stood before this repair':
    { noRequestTimeDecision: true, grantsReadPermissionToTheCaller: true, answersTheQuestionItself: true },
};

// ── run ──────────────────────────────────────────────────────────────────────────────────────────
const up = startRecordingUpstream();
const upstreamPort = await listen(up.server);
const UPSTREAM_BASE = `http://127.0.0.1:${upstreamPort}`;

// The context is built by the module's OWN constructor from an environment, exactly as the server
// builds it. The gate never hand-assembles the object it is testing.
const ctx = privateApiCtx({
  COCKPIT_PRIVATE_API: UPSTREAM_BASE,
  COCKPIT_ALLOWED_ORIGINS: NAMED_IN_ALLOWLIST,
});

const real = http.createServer((req, res) => servePrivateApi(req, res, ctx));
const realPort = await listen(real);

console.log('bridge under test:  http://127.0.0.1:' + realPort);
console.log('recording upstream: ' + UPSTREAM_BASE);
console.log('');
await assess(realPort, up, sink);

// ── the opt-in property, which has no equivalent in a policy fixture ─────────────────────────────
// Absent COCKPIT_PRIVATE_API this is not a route at all. Proven separately because it is a fact
// about configuration rather than about origin, and it must not regress.
{
  const unconfigured = http.createServer((req, res) => servePrivateApi(req, res, privateApiCtx({})));
  const port = await listen(unconfigured);
  up.clear();
  const r = await probe(port, { headers: { origin: FOREIGN } });
  sink('an unconfigured bridge is not a route', r.status === 404, 'status ' + r.status);
  sink('an unconfigured bridge grants no cross-origin read permission', noReadPermission(r));
  sink('an unconfigured bridge reaches no upstream', up.count() === 0, up.count() + ' request(s) recorded');
  await close(unconfigured);
}

// ── the decision function, at its edges ──────────────────────────────────────────────────────────
{
  const d = (origin, host, allowed = []) => originDecision({ origin, host, allowed }).allowed;
  sink('an absent origin is allowed', d(undefined, 'cockpit.example') === true);
  sink('an empty origin is allowed', d('', 'cockpit.example') === true);
  sink('a matching host is allowed whatever it is called', d('https://cockpit.example', 'cockpit.example') === true);
  sink('a matching host and port is allowed', d('https://cockpit.example:8443', 'cockpit.example:8443') === true);
  sink('host comparison ignores case', d('https://COCKPIT.example', 'cockpit.EXAMPLE') === true);
  sink('a different port on the same name is not this host', d('https://cockpit.example:9', 'cockpit.example:8443') === false);
  sink('a name that merely contains this host is not this host', d('https://cockpit.example.evil.test', 'cockpit.example') === false);
  sink('an unparseable origin is refused', d('not a url', 'cockpit.example') === false);
  sink('an opaque origin is refused', d('null', 'cockpit.example') === false);
  sink('an allowlisted origin is allowed against a different host', d('https://a.example', 'b.example', ['https://a.example']) === true);
  sink('an origin absent from a populated allowlist is refused', d('https://c.example', 'b.example', ['https://a.example']) === false);
  const empty = parseAllowedOrigins(undefined);
  sink('the allowlist is empty by default', empty.allowed.length === 0 && empty.warnings.length === 0);
  const bad = parseAllowedOrigins('https://ok.example, not-an-origin, null');
  sink('an unusable allowlist entry is dropped and reported, never silently kept',
    bad.allowed.length === 1 && bad.warnings.length === 2, bad.allowed.join(',') + ' | ' + bad.warnings.length + ' warning(s)');
}

// ── MUTATION — the permissive policies restored in memory; every case must turn assertions RED ───
console.log('\nMUTATION — permissive policy fixtures; every case must turn assertions RED:');
let uncaught = 0, fixturesRun = 0;
const redPerFixture = [];
for (const [name, flags] of Object.entries(FIXTURES)) {
  const fixtureServer = http.createServer(permissiveFixture(UPSTREAM_BASE, flags));
  const port = await listen(fixtureServer);
  let red = 0, total = 0;
  await assess(port, up, (_n, cond) => { total++; if (!cond) red++; });
  await close(fixtureServer);
  fixturesRun++;
  redPerFixture.push({ name, red, total });
  if (total === 0) {
    console.error('  FIXTURE INERT — "' + name + '" executed zero assertions.');
    uncaught++;
  } else if (red > 0) {
    console.log('  caught  ' + red + ' of ' + total + ' assertions RED  <- ' + name);
  } else {
    console.error('  MISSED  0 of ' + total + ' assertions red  <- ' + name);
    uncaught++;
  }
}

await close(real);
await close(up.server);

// ── verdict ──────────────────────────────────────────────────────────────────────────────────────
// Zero executed assertions is a FAILURE, never a pass — a check that asserts nothing also exits 0.
if (ran === 0) {
  console.error('\nORIGIN-BOUNDARY-CHECK FAIL — zero assertions executed; the gate is vacuous.');
  process.exit(1);
}
if (failed || uncaught) {
  console.error('\nORIGIN-BOUNDARY-CHECK FAIL — ' + failed + ' of ' + ran + ' assertions failed, ' +
    uncaught + ' of ' + fixturesRun + ' fixtures not caught.');
  process.exit(1);
}
console.log('\nORIGIN-BOUNDARY-CHECK PASS — ' + ran + ' assertions executed, 0 failed; ' +
  fixturesRun + ' permissive fixtures, all caught (' + redPerFixture.map((f) => f.red + '/' + f.total).join(', ') + ').');
console.log('A request whose origin is not this host is refused before its body is read and before');
console.log('anything reaches the upstream, and no cross-origin read permission is granted to anyone.');
process.exit(0);
