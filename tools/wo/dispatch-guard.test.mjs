test('unreadable input DEFERS rather than bricking every dispatch', () => {
  assert.equal(hookOutput(''), null);
  assert.equal(hookOutput('{not json'), null);
  assert.equal(hookOutput('[]'), null);
});

test('the guard emits ONLY on deny — a permitted dispatch produces no output at all', () => {
  assert.equal(G.toHookOutput({ decision: G.DECISION.DEFER, reason: 'fine' }), null);
  assert.equal(G.toHookOutput(null), null);
  const denied = G.toHookOutput({ decision: G.DECISION.DENY, reason: 'because' });
  assert.equal(denied.hookSpecificOutput.permissionDecision, L_DENY);
});

// ===========================================================================
// MUTATION PROOFS. Each asserts (a) the mutant genuinely stops refusing, and
// (b) the invariant that holds on the real module goes RED against the mutant.
// ===========================================================================

test('MUT-D1 the dispatch tool list emptied — nothing is guarded at all', async () => {
  const mutant = await loadMutant(
    "export const DISPATCH_TOOLS = ['Task'];",
    'export const DISPATCH_TOOLS = [];',
  );
  const raw = payload(`Keel: implement this.\n\n${generatedOrder()}`);
  assert.equal(mutant.toHookOutput(mutant.runHook(raw)), null, 'mutant should guard nothing');
  await assertMutantBreaks(
    mutant,
    (m) => assert.ok(m.toHookOutput(m.runHook(raw)), 'an unready order must be denied'),
    'MUT-D1 the subagent dispatch tool must be guarded',
  );
});

test('MUT-D2 the readiness verdict ignored — an unready order reaches the worker', async () => {
  const mutant = await loadMutant(
    '    const unready = assessed.filter((a) => !a.assessment.ready);',
    '    const unready = [];',
  );
  const raw = payload(`Keel: implement this.\n\n${generatedOrder()}`);
  assert.equal(mutant.toHookOutput(mutant.runHook(raw)), null, 'mutant should let the unready order through');
  await assertMutantBreaks(
    mutant,
    (m) => assert.ok(m.toHookOutput(m.runHook(raw))),
    'MUT-D2 an order the validator calls NOT READY must be denied at dispatch',
  );
});

test('MUT-D3 the free-form bypass reopened — a Work Order sent as prose is allowed', async () => {
  const mutant = await loadMutant(
    '  if (ORDER_PHRASE.test(String(text ?? \'\')) && fields.length >= 1) return { shaped: true, fields };',
    '  if (false) return { shaped: true, fields };',
  );
  const freeform = 'WORK ORDER — do the thing.\nprivate_surface: none\ngovernance_head: 8bc5340';
  const raw = payload(freeform);
  assert.equal(mutant.toHookOutput(mutant.runHook(raw)), null, 'mutant should reopen the bypass');
  await assertMutantBreaks(
    mutant,
    (m) => assert.ok(m.toHookOutput(m.runHook(raw))),
    'MUT-D3 sending a worker directly must not bypass the validator',
  );
});

test('MUT-D4 the provenance marker dropped from order detection — any cited doc becomes an order', async () => {
  const mutant = await loadMutant(
    '    if (!String(content).includes(ORDER_MARKER)) continue;',
    '    if (false) continue;',
  );
  const raw = payload('Veritas: review Deliverables/2026-08-04-proofline-wayfinder-plan.md at governance head 8bc5340.');
  const out = mutant.toHookOutput(mutant.runHook(raw));
  assert.ok(out, 'mutant should mistake a Wayfinder map for a Work Order and deny the assurance dispatch');
  await assertMutantBreaks(
    mutant,
    (m) => assert.equal(m.toHookOutput(m.runHook(raw)), null),
    'MUT-D4 only a document carrying the generator marker is a Work Order',
  );
});

test('MUT-D5 the deny output suppressed — the decision is made and never delivered', async () => {
  const mutant = await loadMutant(
    "  if (!result || result.decision !== DECISION.DENY) return null;",
    '  if (true) return null;',
  );
  const raw = payload(`Keel: implement this.\n\n${generatedOrder()}`);
  assert.equal(
    mutant.runHook(raw).decision,
    G.DECISION.DENY,
    'mutant still DECIDES to deny — it simply stops telling the host',
  );
  assert.equal(mutant.toHookOutput(mutant.runHook(raw)), null, 'mutant should swallow the refusal');
  await assertMutantBreaks(
    mutant,
    (m) => assert.ok(m.toHookOutput(m.runHook(raw))),
    'MUT-D5 a refusal the host never receives is not a refusal',
  );
});
