test('the forbidden value is REAL — `ask` is how this estate deliberately prompts Warwick', () => {
  // Corroborated against the proven idiom rather than asserted. If `ask` ever stops being the
  // prompting value, this test is where that shows up.
  const wg = norm(readFileSync(join(REPO, L_WORKTREE_GUARD), 'utf8'));
  assert.match(wg, /export const DECISION = \{[^}]*ASK: 'ask'[^}]*\};/, `${L_WORKTREE_GUARD} must still define ASK`);
  assert.match(wg, /const HOOK_DECISION = \{[\s\S]{0,200}\[DECISION\.ASK\]: 'ask',/, 'ASK must still be EMITTED as a permissionDecision');
  assert.match(wg, /PUSH_ASK_REASON = 'Warwick approval required for push to main\.'/, 'ASK must still be the value that asks Warwick');
});

test('AC1 — EVERY decision-producing path is enumerated, and none can emit the prompting value', () => {
  const code = codeOnly(SRC);
  const produced = [...code.matchAll(/\bdecision:\s*([A-Za-z0-9_.]+)/g)].map((m) => m[1]);
  assert.equal(
    produced.length,
    L_DECISION_PATH_COUNT,
    `decision-producing paths changed (${produced.length} found, ${L_DECISION_PATH_COUNT} pinned) — enumerate the new one and classify it before shipping`,
  );
  const permittedTokens = ['DECISION.DENY', 'DECISION.DEFER'];
  for (const token of produced) {
    assert.ok(permittedTokens.includes(token), `a decision path produces an unclassified value: ${token}`);
  }

  // The enum itself is closed: no ASK, no ALLOW. This guard denies, or it stands aside.
  assert.deepEqual(G.DECISION, { DENY: 'deny', DEFER: 'defer' });
  assert.equal(Object.isFrozen(G.DECISION), true, 'the decision enum must not be mutable at runtime');
  assert.equal(Object.values(G.DECISION).includes(L_PROMPTING_DECISION), false);
  assert.equal(Object.values(G.DECISION).includes('allow'), false, 'this guard never speaks for the human in either direction');

  // The emission set is closed and frozen.
  assert.deepEqual(G.PERMITTED_HOOK_DECISIONS, L_PERMITTED_HOOK_DECISIONS);
  assert.equal(Object.isFrozen(G.PERMITTED_HOOK_DECISIONS), true);
  assert.deepEqual(Object.values(G.HOOK_DECISION), L_PERMITTED_HOOK_DECISIONS);
  assert.equal(Object.isFrozen(G.HOOK_DECISION), true);
  assert.equal(G.HOOK_DECISION[L_PROMPTING_DECISION], undefined, 'nothing may map to the prompting value');
  assert.equal(G.PROMPTING_HOOK_DECISION, L_PROMPTING_DECISION);

  // The allowing literal appears nowhere in executable code at all.
  for (const forbidden of ["'allow'", '"allow"']) {
    assert.equal(code.includes(forbidden), false, `executable code carries the literal ${forbidden}`);
  }
  // The prompting literal appears EXACTLY ONCE, on the line that declares it forbidden, and the
  // constant is never referenced again — so it cannot be reached by any emission path.
  const askLines = code.split('\n').filter((l) => l.includes(`'${L_PROMPTING_DECISION}'`) || l.includes(`"${L_PROMPTING_DECISION}"`));
  assert.equal(askLines.length, 1, `the prompting literal appears on ${askLines.length} executable lines: ${askLines.join(' | ')}`);
  assert.match(askLines[0], /^export const PROMPTING_HOOK_DECISION = /);
  const uses = code.split('PROMPTING_HOOK_DECISION').length - 1;
  assert.equal(uses, 1, 'PROMPTING_HOOK_DECISION is declared for the test to pin, and must never be USED');
});

test('AC1 — every reachable path EXERCISED through the real hook entry point emits deny or nothing', () => {
  const unready = `Keel: implement this.\n\n${generatedOrder()}`;
  const ready = `Keel: implement this.\n\n${authoredOrder()}`;
  const shaped = 'WORK ORDER — do the thing.\nprivate_surface: none\ncredential_scope: none';

  // One scenario per enumerated decision path, named so a reader can check the mapping.
  const scenarios = [
    ['decideDispatch: not a dispatch tool', () => hookOutput(payload(unready, { tool: 'Bash' }))],
    ['decideDispatch: carried order is UNREADY', () => hookOutput(payload(unready))],
    ['decideDispatch: carried order is READY', () => hookOutput(payload(ready))],
    ['decideDispatch: Work-Order-shaped, no generated order', () => hookOutput(payload(shaped))],
    ['decideDispatch: not Work-Order-shaped at all', () => hookOutput(payload('Pax: research something. governance head 8bc5340.'))],
    ['runHook: input unreadable', () => hookOutput('{not json')],
    ['runHook: internal throw', () => hookOutput(payload(unready), {
      read: () => { throw new Error('forced internal failure'); },
    })],
  ];
  assert.equal(scenarios.length, L_DECISION_PATH_COUNT, 'one exercised scenario per enumerated decision path');

  let emitted = 0;
  let silent = 0;
  for (const [label, run] of scenarios) {
    const out = run();
    if (out === null) { silent++; continue; }
    const d = out.hookSpecificOutput.permissionDecision;
    assert.notEqual(d, L_PROMPTING_DECISION, `PATH PROMPTS WARWICK: ${label}`);
    assert.ok(L_PERMITTED_HOOK_DECISIONS.includes(d), `path emitted an unpermitted decision (${d}): ${label}`);
    emitted++;
  }
  assert.equal(emitted + silent, L_DECISION_PATH_COUNT);
  assert.ok(emitted > 0, 'a run in which nothing was ever emitted proves nothing about what is emitted');
});

test('AC1 — the emission function cannot be COERCED into prompting, whatever it is handed', () => {
  for (const decision of [L_PROMPTING_DECISION, 'allow', 'ASK', 'Deny', '', null, undefined, 0, 'defer']) {
    assert.equal(G.toHookOutput({ decision, reason: 'forged' }), null, `forged decision emitted: ${String(decision)}`);
  }
  // Inherited object properties must not become decisions — the frozen map is not enough on its
  // own, which is why the permitted-set check sits behind it.
  for (const decision of ['toString', 'constructor', '__proto__', 'hasOwnProperty']) {
    assert.equal(G.toHookOutput({ decision, reason: 'forged' }), null, `prototype key emitted: ${decision}`);
  }
  const real = G.toHookOutput({ decision: G.DECISION.DENY, reason: 'because' });
  assert.equal(real.hookSpecificOutput.permissionDecision, L_DENY, 'the one permitted emission must still work');
});

