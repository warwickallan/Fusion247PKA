test('a denied dispatch names the ABSENT and MALFORMED fields, never a bare "not ready"', () => {
  const broken = authoredOrder()
    .replace(/^private_surface: .*$/m, '')
    .replace(/^document_impact: \[\]$/m, 'document_impact: services/x/README.md (owner: keel) · Deliverables/y.md (owner: larry)');
  const out = hookOutput(payload(`Keel: implement this.\n\n${broken}`));
  assert.ok(out, 'an order with an absent and a malformed field must be denied');
  const reason = out.hookSpecificOutput.permissionDecisionReason;
  assert.equal(out.hookSpecificOutput.permissionDecision, L_DENY);
  assert.match(reason, /ABSENT[^;]*private_surface/, 'the absent field must be named, and labelled ABSENT');
  assert.match(reason, /MALFORMED/, 'the shape defect must be labelled MALFORMED, not merged with absence');
  assert.match(reason, /document_impact \(expected list, found scalar\)/, 'and it must say what was expected and what was found');
  assert.match(reason, /node tools\/wo\/envelope\.mjs --assess/, 'the refusal must say how to re-check the fix');
});

