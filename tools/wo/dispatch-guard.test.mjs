async function loadMutantAll(pairs) {
  let mutated = SRC;
  for (const [find, replace] of pairs) {
    assert.ok(mutated.includes(find), `mutation target absent from source: ${JSON.stringify(find)}`);
    mutated = mutated.replace(find, replace);
  }
  mutated = mutated.replace("from './envelope.mjs'", `from '${ENVELOPE_URL}'`);
  assert.notEqual(mutated, SRC, 'mutation did not change the source');
  return import(`data:text/javascript;base64,${Buffer.from(mutated, 'utf8').toString('base64')}`);
}

async function loadMutant(find, replace) {
  return loadMutantAll([[find, replace]]);
}

async function assertMutantBreaks(mutant, fn, label) {
  let broke = false;
  try {
    fn(mutant);
  } catch {
    broke = true;
  }
  assert.equal(broke, true, `MUTATION SURVIVED — the control is decorative: ${label}`);
}

