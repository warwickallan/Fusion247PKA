// tools/wo/dispatch-guard.test.mjs — proofs for 4F CAPA item 8.
//
// The claim under test is narrow and load-bearing: THE DISPATCH EVENT ITSELF REFUSES AN
// UNREADY WORK ORDER. Everything here is written against the real `PreToolUse` payload shape
// the host sends, not against a convenient internal API — a guard proven only through its own
// helpers proves nothing about the production event.
//
// Two disciplines, inherited from envelope.test.mjs and not re-argued here:
//   1. Invariants are pinned to literals HELD IN THIS FILE.
//   2. Every control is MUTATION-TESTED. A check no test can fail is decorative.
//
// Mutants load through a `data:` URL, so this suite writes nothing outside the declared file
// surface. dispatch-guard.mjs has ONE relative import, so the mutant's specifier is rewritten
// to an absolute file URL before loading — the alternative (writing mutants to disk) would put
// bytes outside the surface for no gain.

